do $$
declare
  v_table text;
  v_sequence text;
  v_identity text;
begin
  for v_table, v_sequence in
    select * from (values
      ('projects', 'projects_id_seq'),
      ('participants', 'participants_id_seq'),
      ('tasks', 'tasks_id_seq')
    ) as ids(table_name, sequence_name)
  loop
    select is_identity into v_identity
    from information_schema.columns
    where table_schema = 'public' and table_name = v_table and column_name = 'id';
    if v_identity = 'NO' then
      execute format('create sequence if not exists public.%I', v_sequence);
      execute format(
        'alter table public.%I alter column id set default nextval(%L::regclass)',
        v_table, 'public.' || v_sequence
      );
      execute format(
        'select setval(%L::regclass, coalesce((select max(id) from public.%I), 0) + 1, false)',
        'public.' || v_sequence, v_table
      );
    end if;
  end loop;
end
$$;


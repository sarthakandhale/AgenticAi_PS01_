drop function if exists public.create_followup_if_allowed(text, text, text, text, integer);
create or replace function public.create_followup_if_allowed(
  p_task_id bigint,
  p_project_id bigint,
  p_participant_id bigint,
  p_message_text text,
  p_max_per_day integer
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  if p_max_per_day < 1 then raise exception 'Daily follow-up limit must be positive'; end if;
  perform pg_advisory_xact_lock(hashtext(p_participant_id::text)::bigint);
  if not exists (
    select 1 from public.tasks
    where id = p_task_id
      and project_id = p_project_id
      and owner_id = p_participant_id
  ) then
    raise exception 'Task is not assigned to this participant';
  end if;
  if (
    select count(*) from public.followups
    where participant_id = p_participant_id
      and requested_at >= now() - interval '24 hours'
  ) >= p_max_per_day then
    raise exception 'Daily follow-up limit reached for this participant';
  end if;
  if exists (
    select 1 from public.followups
    where task_id = p_task_id
      and requested_at >= now() - interval '1 hour'
  ) then
    raise exception 'A follow-up was sent for this task within the last hour';
  end if;

  insert into public.followups (
    task_id, project_id, participant_id, message_text, status
  )
  values (p_task_id, p_project_id, p_participant_id, p_message_text, 'AWAITING_REPLY')
  returning id into v_id;
  return v_id;
end;
$$;

drop function if exists public.apply_reply_decision(text, text, text, uuid, uuid, text, jsonb, text, text);
create or replace function public.apply_reply_decision(
  p_project_id bigint,
  p_task_id bigint,
  p_participant_id bigint,
  p_message_id uuid,
  p_followup_id uuid,
  p_evidence text,
  p_analysis jsonb,
  p_next_status text,
  p_blocker text
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_next_status is not null and p_next_status not in ('IN_PROGRESS', 'BLOCKED', 'COMPLETE') then
    raise exception 'Invalid task status';
  end if;

  insert into public.task_events (
    project_id, task_id, participant_id, event_type, evidence,
    message_id, analysis, previous_status, next_status
  )
  values (
    coalesce(p_project_id, (select project_id from public.tasks where id = p_task_id)),
    p_task_id,
    p_participant_id,
    'telegram_reply_analysis',
    p_evidence,
    p_message_id,
    p_analysis,
    case when p_task_id is null then null else
      (select status from public.tasks where id = p_task_id)
    end,
    p_next_status
  );

  if p_next_status is not null and p_task_id is not null then
    update public.tasks
    set status = case p_next_status
          when 'IN_PROGRESS' then 'in_progress'
          when 'BLOCKED' then 'blocked'
          when 'COMPLETE' then 'completed'
        end,
        blocker = case when p_next_status = 'BLOCKED' then p_blocker else null end,
        updated_at = now()
    where id = p_task_id and owner_id = p_participant_id;
    if not found then raise exception 'Task is not assigned to the participant'; end if;
  end if;

  if p_followup_id is not null then
    update public.followups
    set status = 'REPLIED', replied_at = now()
    where id = p_followup_id and participant_id = p_participant_id;
  end if;

  update public.telegram_messages
  set task_id = p_task_id,
      processing_status = 'PROCESSED',
      processing_error = null
  where id = p_message_id;
end;
$$;

